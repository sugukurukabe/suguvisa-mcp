import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { z } from "zod";
import * as path from "path";
import * as fs from "fs";
import XlsxPopulate from "xlsx-populate";

const OUTPUT_DIR = path.resolve(process.cwd(), "output");

/**
 * テンプレートなしでプログラムから美しい定期報告エクセルを生成する関数
 */
export async function createOfflineExcel(company_name: string, reporting_year: number, paper_form_data: any[]): Promise<string> {
  // 出力先ディレクトリの確保
  if (!fs.existsSync(OUTPUT_DIR)) {
    fs.mkdirSync(OUTPUT_DIR, { recursive: true });
  }

  const timestamp = new Date().toISOString().replace(/[:.]/g, "-");
  const outputPath = path.join(OUTPUT_DIR, `定期報告_${company_name}_${reporting_year}_${timestamp}.xlsx`);

  const workbook = await XlsxPopulate.fromBlankAsync();
  const sheet = workbook.sheet(0);
  sheet.name("定期報告データ（紙提出用）");

  // タイトル等
  sheet.cell("A1").value(`特定技能外国人 定期（随時）報告データ（${reporting_year}年度）`);
  sheet.cell("A1").style({ bold: true, fontSize: 14 });
  sheet.cell("A2").value(`所属機関: ${company_name} 様`);

  // ヘッダー行を作成
  const headers = [
    "在留カード番号", "氏(ローマ字)", "名(ローマ字)", "生年月日", "性別", 
    "出勤日数", "有給取得日数", "平均月額報酬額", 
    "離職年月日", "離職理由", "直近面談日", "支援状況"
  ];

  const headerRow = 4;
  headers.forEach((header, index) => {
    const cell = sheet.cell(headerRow, index + 1);
    cell.value(header);
    // スタイル適用
    cell.style({
      bold: true,
      fill: "0052cc",     // スグクルブルー
      fontColor: "ffffff", // 白抜き
      border: true,
      horizontalAlignment: "center"
    });
  });

  // 列の幅をある程度自動調整
  const columnWidths = [18, 15, 15, 12, 6, 10, 15, 16, 14, 18, 14, 12];
  columnWidths.forEach((width, index) => {
    sheet.column(index + 1).width(width);
  });

  // データを流し込む（5行目から）
  let rowIndex = 5;
  for (const data of paper_form_data) {
    const rowCells = [
      data.residence_card_number || "",
      data.family_name_romaji || "",
      data.given_name_romaji || "",
      data.date_of_birth || "",
      data.sex === "1" ? "男" : (data.sex === "2" ? "女" : data.sex || ""),
      data.working_days || "",
      data.paid_leave_days || "",
      data.monthly_salary_average || "",
      data.resignation_date || "",
      data.resignation_reason || "",
      data.support_interview_date || "",
      data.support_status_code === "1" ? "1:適切に実施" : data.support_status_code === "2" ? "2:全部委託" : data.support_status_code === "3" ? "3:一部未実施" : ""
    ];

    rowCells.forEach((val, i) => {
      const cell = sheet.cell(rowIndex, i + 1);
      cell.value(val);
      cell.style({ border: true });
    });
    rowIndex++;
  }

  // Excelファイルとして保存
  await workbook.toFileAsync(outputPath);
  return outputPath;
}

export function registerGenerateAnnualReportOffline(server: McpServer) {
  server.tool(
    "generate_annual_report_offline",
    "【定期届出Excel生成】オンライン届出未対応の所属機関向けに、紙提出用の定期報告書をExcel形式で自動出力。JSONデータからセル配置まで全自動。 / Generates offline Excel annual report for paper submission by organizations not using the online system.",
    {
      company_name: z.string().describe("所属機関名 / Company name"),
      reporting_year: z.number().describe("報告年度（例: 2026） / Reporting year"),
      paper_form_data: z.array(z.any()).describe(
        "generate_annual_report_csv で生成された paper_form_data (JSON配列) / The JSON paper form data generated by generate_annual_report_csv"
      )
    },
    { readOnlyHint: false, destructiveHint: false, openWorldHint: false },
    async ({ company_name, reporting_year, paper_form_data }) => {
      try {
        const outputPath = await createOfflineExcel(company_name, reporting_year, paper_form_data);
        return {
          content: [{
            type: "text" as const,
            text: JSON.stringify({
              status: "success",
              message: "オフライン用定期報告書（Excel）を生成しました",
              output_path: outputPath,
              processed_records: paper_form_data.length,
              company_name,
              reporting_year,
            }, null, 2)
          }]
        };
      } catch (error: any) {
        return {
          content: [{
            type: "text" as const,
            text: JSON.stringify({
              status: "error",
              message: "Excelファイルの生成に失敗しました / Failed to generate Excel file",
              error: String(error)
            }, null, 2)
          }]
        };
      }
    }
  );
}
